#!/usr/bin/env node
/**
 * Generate the declared-configuration table from `appConfigSchema`.
 *
 * The point of step 9 in `plans/core-configuration-attack-plan.md`: adding an
 * environment variable by hand costs entries in several files, so declaring a
 * field has to cost less than that or nobody will. This writes the table for
 * every declared field, so a new field documents itself.
 *
 * The surrounding prose in the target file is hand-written and stays that way —
 * only the block between the markers is owned here.
 *
 * `--check` verifies the block is current without writing, which is what
 * `pnpm guard:config-docs` runs in CI.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { describeConfigFields } from "../packages/core/src/app-config/describe.js";

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

const TARGET = path.join(REPO_ROOT, "docs", "environment-variables.md");
const BEGIN = "<!-- BEGIN GENERATED: declared-app-config -->";
const END = "<!-- END GENERATED: declared-app-config -->";

function formatDefault(value: unknown): string {
  if (value === undefined) return "—";
  return `\`${JSON.stringify(value)}\``;
}

function renderTable(): string {
  const fields = describeConfigFields();
  const rows = fields.map((field) => {
    const env = field.env.length
      ? field.env.map((key) => `\`${key}\``).join(", ")
      : "—";
    return `| \`${field.path}\` | ${env} | ${field.type} | ${formatDefault(field.defaultValue)} | ${field.doc ?? ""} |`;
  });

  return [
    BEGIN,
    "",
    "<!-- Generated by `pnpm sync:config-docs`. Do not edit by hand. -->",
    "",
    "## Declared app configuration",
    "",
    "Every field below is set with `defineAppConfig()` from server code. The",
    "environment variable is a declared alias for the same field, listed in the",
    "order it is consulted; app configuration wins over any of them. Fields with",
    "no alias are settable only in code.",
    "",
    "| Field | Environment aliases | Type | Default | Description |",
    "| ----- | ------------------- | ---- | ------- | ----------- |",
    ...rows,
    "",
    END,
  ].join("\n");
}

function main(): void {
  const check = process.argv.includes("--check");
  const source = readFileSync(TARGET, "utf8");
  const block = renderTable();

  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);

  let next: string;
  if (start === -1 || end === -1) {
    if (check) {
      console.error(
        `[sync-config-docs] ${path.relative(REPO_ROOT, TARGET)} has no generated block. Run \`pnpm sync:config-docs\`.`,
      );
      process.exit(1);
    }
    next = `${source.trimEnd()}\n\n${block}\n`;
  } else {
    if (end < start) {
      console.error(
        "[sync-config-docs] generated block markers are out of order.",
      );
      process.exit(2);
    }
    next = source.slice(0, start) + block + source.slice(end + END.length);
  }

  if (next === source) {
    console.log("[sync-config-docs] up to date");
    return;
  }
  if (check) {
    console.error(
      "[sync-config-docs] declared configuration docs are stale. Run `pnpm sync:config-docs`.",
    );
    process.exit(1);
  }
  writeFileSync(TARGET, next);
  console.log(
    `[sync-config-docs] wrote ${describeConfigFields().length} fields to ${path.relative(REPO_ROOT, TARGET)}`,
  );
}

main();
