/**
 * Writes packages/core/src/db/schema-snapshot.generated.ts: the framework
 * schema a fresh release produces step by step, which fresh databases install
 * in one transaction instead of replaying every migration.
 *
 * Run after adding or changing a store migration (CI checks it is current).
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";

const SNAPSHOT_FILE = "packages/core/src/db/schema-snapshot.generated.ts";
const LEDGER_TABLES = new Set([
  "_an_store_migrations",
  "_an_store_migration_lock",
]);

const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "schema-snapshot-"));
process.env.DATABASE_URL = `pglite:${dataDir}`;

const { closeDbExec, getDbExec } =
  await import("../packages/core/src/db/client.js");
const { withMigrationRuntime } =
  await import("../packages/core/src/db/migration-runtime.js");
const { __setSchemaSnapshotForTests } =
  await import("../packages/core/src/db/store-registry.js");
const { dumpSchemaStatements } =
  await import("../packages/core/src/db/schema-catalog.js");
const { runFrameworkReleaseMigrations } =
  await import("../packages/core/src/server/release-migrations.js");
const { FRAMEWORK_STORES } =
  await import("../packages/core/src/db/store-registry.generated.js");

try {
  // The snapshot is what the step-by-step path produces, never itself.
  __setSchemaSnapshotForTests(null);
  await withMigrationRuntime(() => runFrameworkReleaseMigrations());
  const exec = getDbExec();
  const statements = await dumpSchemaStatements(exec, {
    skipTable: (table) => LEDGER_TABLES.has(table),
  });
  const tables = (
    await exec.execute(
      "SELECT tablename FROM pg_tables WHERE schemaname = 'public' ORDER BY tablename",
    )
  ).rows
    .map((row) => String(row.tablename))
    .filter((table) => !LEDGER_TABLES.has(table));
  const migrations = (
    await exec.execute(
      "SELECT store_id, name, checksum FROM _an_store_migrations WHERE kind = 'schema' ORDER BY store_id, name",
    )
  ).rows.map((row) => [
    String(row.store_id),
    String(row.name),
    row.checksum == null ? null : String(row.checksum),
  ]);
  const covered = new Set(
    migrations.map(([storeId, name]) => `${storeId}\0${name}`),
  );
  const bootLists: Array<[string, number, string | null]> = [];
  for (const [, load] of FRAMEWORK_STORES) {
    const store = await load();
    for (const migration of store.migrations) {
      const legacy = migration.legacy;
      if (!legacy?.ranAtBoot) continue;
      if (!covered.has(`${store.id}\0${migration.name}`)) continue;
      bootLists.push([legacy.table, legacy.version, legacy.name ?? null]);
    }
  }
  const body = [
    "// Generated by scripts/gen-schema-snapshot.ts. Do not edit; run",
    "// `pnpm gen:schema-snapshot` after changing a store migration.",
    "// guard:allow-unreleased-schema — schema snapshot text, executed only by the store runner",
    'import type { SchemaSnapshot } from "./store-registry.js";',
    "",
    `export const SCHEMA_SNAPSHOT: SchemaSnapshot = ${JSON.stringify(
      { statements, tables, migrations, bootLists },
      null,
      2,
    )};`,
    "",
  ].join("\n");
  fs.writeFileSync(SNAPSHOT_FILE, body, "utf8");
  console.log(
    `Wrote ${SNAPSHOT_FILE} (${statements.length} statements, ${tables.length} tables, ${migrations.length} migrations).`,
  );
} finally {
  await closeDbExec();
  fs.rmSync(dataDir, { recursive: true, force: true });
}
