export function listBuiltInSlideThemeSummaries(): BuiltInSlideThemeSummary[] {
  return themes.map(({ id, name, description, mode, preview }) => ({
    id,
    name,
    description,
    mode,
    preview,
  }));
}

export function getBuiltInSlideTheme(
  id: string,
): BuiltInSlideTheme | undefined {
  const theme = themes.find((candidate) => candidate.id === id);
  return theme ? structuredClone(theme) : undefined;
}
