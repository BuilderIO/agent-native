import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import * as esbuild from "esbuild";

import { nativeEffectAnimationCapability } from "../../../../shared/native-effect-animation-capability";
import { NATIVE_EFFECT_DEFINITION_CATALOG } from "../../../../shared/native-effect-presets";
import { nativeEffectExecutionPayload } from "../../../../shared/native-effect-trust";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const designRoot = resolve(__dirname, "../../../..");
const bridgeDir = __dirname;
const generatedDir = join(designRoot, ".generated", "bridge");

const GENERATED_BANNER = `// AUTO-GENERATED by bridge/codegen.ts — do not edit manually.
// Run: pnpm exec tsx app/components/design/bridge/codegen.ts
`;

function writeGeneratedFile(path: string, source: string): boolean {
  const formatted = execFileSync(
    "pnpm",
    ["exec", "oxfmt", "--stdin-filepath", path],
    {
      cwd: designRoot,
      encoding: "utf-8",
      input: source,
      maxBuffer: 32 * 1024 * 1024,
    },
  );
  let current: string | undefined;
  try {
    current = readFileSync(path, "utf-8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  if (current === formatted) return false;
  writeFileSync(path, formatted, "utf-8");
  return true;
}

function writeBuiltinMetadata(): void {
  const versions = new Set<string>();
  const hashes = new Set<string>();
  const metadata = NATIVE_EFFECT_DEFINITION_CATALOG.map((definition) => {
    const version = `${definition.id}@${definition.version}`;
    if (versions.has(version))
      throw new Error(`Duplicate built-in native definition ${version}`);
    versions.add(version);
    const capability = nativeEffectAnimationCapability(definition);
    if (capability === "unknown")
      throw new Error(`Unreviewed built-in native definition ${version}`);
    const hash = createHash("sha256")
      .update(JSON.stringify(nativeEffectExecutionPayload(definition)), "utf8")
      .digest("hex");
    if (hashes.has(hash))
      throw new Error(`Duplicate built-in native execution hash ${hash}`);
    hashes.add(hash);
    return { hash, capability };
  }).sort((a, b) => (a.hash < b.hash ? -1 : a.hash > b.hash ? 1 : 0));
  const rows = metadata.map(
    ({ hash, capability }) => `  [\n    "${hash}",\n    "${capability}",\n  ],`,
  );
  writeGeneratedFile(
    join(generatedDir, "native-builtin-metadata.generated.ts"),
    `${GENERATED_BANNER}\nexport const nativeBuiltinExecutionMetadata = [\n${rows.join("\n")}\n] as const;\n`,
  );
}

async function compileBridge(srcFile: string): Promise<string> {
  const result = await esbuild.build({
    entryPoints: [srcFile],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2020",
    write: false,
    external: [],
  });

  if (result.errors.length > 0) {
    const msgs = await esbuild.formatMessages(result.errors, { kind: "error" });
    throw new Error(`esbuild error for ${srcFile}:\n${msgs.join("\n")}`);
  }

  const output = result.outputFiles[0];
  if (!output) throw new Error(`No output from esbuild for ${srcFile}`);
  return output.text;
}

function bridgeName(filename: string): string {
  return filename.replace(/\.bridge\.ts$/, "");
}

function generatedModuleSrc(name: string, compiled: string): string {
  const escaped = compiled
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
  return `${GENERATED_BANNER}
/** Compiled IIFE string for ${name}.bridge.ts — inject into an iframe via srcdoc or a <script> tag. */
export const ${camelCase(name)}BridgeScript: string = \`${escaped}\`;
`;
}

function camelCase(name: string): string {
  return name.replace(/[-_]([a-z])/g, (_, c: string) => c.toUpperCase());
}

async function runCodegen(): Promise<void> {
  mkdirSync(generatedDir, { recursive: true });
  writeBuiltinMetadata();
  const bridgeFiles = readdirSync(bridgeDir).filter((f) =>
    f.endsWith(".bridge.ts"),
  );

  if (bridgeFiles.length === 0) {
    console.log("[bridge/codegen] No *.bridge.ts files found.");
    return;
  }

  for (const filename of bridgeFiles) {
    const srcPath = join(bridgeDir, filename);
    const name = bridgeName(filename);
    const outPath = join(generatedDir, `${name}.generated.ts`);

    console.log(`[bridge/codegen] Compiling ${filename} ...`);
    const compiled = await compileBridge(srcPath);
    const src = generatedModuleSrc(name, compiled);
    const changed = writeGeneratedFile(outPath, src);
    console.log(
      `[bridge/codegen] → .generated/bridge/${name}.generated.ts${changed ? "" : " (unchanged)"}`,
    );
  }

  console.log("[bridge/codegen] Done.");
}

runCodegen().catch((err) => {
  console.error("[bridge/codegen] FAILED:", err);
  process.exit(1);
});
