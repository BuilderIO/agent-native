const canonicalPayloadByVersion = new Map(
  NATIVE_EFFECT_DEFINITION_CATALOG.map((definition) => [
    `${definition.id}@${definition.version}`,
    JSON.stringify(nativeEffectExecutionPayload(definition)),
  ]),
);

export function nativeEffectAnimationCapability(
  definition: EffectDefinition,
): NativeEffectAnimationCapability {
  const key = `${definition.id}@${definition.version}`;
  const canonicalPayload = canonicalPayloadByVersion.get(key);
  if (
    canonicalPayload === undefined ||
    canonicalPayload !==
      JSON.stringify(nativeEffectExecutionPayload(definition))
  )
    return "unknown";
  const staticReviewed = STATIC_BUILTIN_VERSIONS.has(key);
  const animatedReviewed = ANIMATED_BUILTIN_VERSIONS.has(key);
  if (staticReviewed === animatedReviewed) return "unknown";
  return staticReviewed ? "static" : "animated";
}
