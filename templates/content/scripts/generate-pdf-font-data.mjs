#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const fonts = [
  { constName: "SPECTRAL_REGULAR_BASE64", file: "Spectral-Regular.ttf" },
  { constName: "SPECTRAL_ITALIC_BASE64", file: "Spectral-Italic.ttf" },
  { constName: "SPECTRAL_BOLD_BASE64", file: "Spectral-Bold.ttf" },
  { constName: "SPECTRAL_BOLD_ITALIC_BASE64", file: "Spectral-BoldItalic.ttf" },
];

const banner = `// Generated by scripts/generate-pdf-font-data.mjs from assets/fonts; do not edit by hand.
// Spectral, embedded so serif PDFs don't depend on serverless asset tracing.
// See assets/fonts/LICENSE_SPECTRAL for licensing. Regenerate with:
//   node scripts/generate-pdf-font-data.mjs
`;

const body = fonts
  .map(({ constName, file }) => {
    const bytes = readFileSync(
      fileURLToPath(new URL(`../assets/fonts/${file}`, import.meta.url)),
    );
    return `export const ${constName} =\n  "${bytes.toString("base64")}";`;
  })
  .join("\n\n");

const out = fileURLToPath(
  new URL("../server/lib/spectral-fonts.generated.ts", import.meta.url),
);
writeFileSync(out, `${banner}\n${body}\n`);
console.log(`Wrote ${out}`);
