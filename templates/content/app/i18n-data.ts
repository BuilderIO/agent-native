function mergeMessagesForLocale(
  locale: Exclude<LocaleCode, "en-US">,
  overrides: PartialMessages,
  bundle: ContentLocaleBundle,
): Messages {
  const defaultRawLiteralOverrides = esESRawLiteralOverrides;
  const localeRawLiteralOverrides = bundle.rawLiterals;
  const rawLiteralOverrides = {
    ...defaultRawLiteralOverrides,
    ...localeRawLiteralOverrides,
    root: {
      ...defaultRawLiteralOverrides.root,
      ...localeRawLiteralOverrides?.root,
    },
    team: {
      ...defaultRawLiteralOverrides.team,
      ...localeRawLiteralOverrides?.team,
    },
    settings: {
      ...defaultRawLiteralOverrides.settings,
      ...localeRawLiteralOverrides?.settings,
    },
    publicDocument: {
      ...defaultRawLiteralOverrides.publicDocument,
      ...localeRawLiteralOverrides?.publicDocument,
    },
    database: {
      ...defaultRawLiteralOverrides.database,
      ...localeRawLiteralOverrides?.database,
    },
    localFiles: {
      ...defaultRawLiteralOverrides.localFiles,
      ...localeRawLiteralOverrides?.localFiles,
    },
    empty: {
      ...defaultRawLiteralOverrides.empty,
      ...localeRawLiteralOverrides?.empty,
    },
    editor: {
      ...defaultRawLiteralOverrides.editor,
      ...localeRawLiteralOverrides?.editor,
      media: {
        ...defaultRawLiteralOverrides.editor?.media,
        ...localeRawLiteralOverrides?.editor?.media,
      },
      toolbar: {
        ...defaultRawLiteralOverrides.editor?.toolbar,
        ...localeRawLiteralOverrides?.editor?.toolbar,
      },
    },
    sidebar: {
      ...defaultRawLiteralOverrides.sidebar,
      ...localeRawLiteralOverrides?.sidebar,
    },
  };
  const base = mergeMessages({
    ...overrides,
    creativeContext: creativeContextMessagesByLocale[locale],
  });
  return {
    ...base,
    comments: {
      ...base.comments,
      ...bundle.comments,
      ...bundle.reviewDiscussions,
    },
    landing: { ...base.landing, ...bundle.landing },
    root: { ...base.root, ...rawLiteralOverrides.root },
    team: { ...base.team, ...rawLiteralOverrides.team },
    settings: { ...base.settings, ...rawLiteralOverrides.settings },
    publicDocument: {
      ...base.publicDocument,
      ...rawLiteralOverrides.publicDocument,
    },
    database: { ...base.database, ...rawLiteralOverrides.database },
    localFiles: { ...base.localFiles, ...rawLiteralOverrides.localFiles },
    empty: { ...base.empty, ...rawLiteralOverrides.empty },
    editor: {
      ...base.editor,
      ...rawLiteralOverrides.editor,
      underline: underlineMessagesByLocale[locale],
      suggestionFormattingUnsupported:
        suggestionFormattingMessagesByLocale[locale][0]!,
      suggestionFormattingBaselineUnsupported:
        suggestionFormattingMessagesByLocale[locale][1]!,
      removeLink: removeLinkMessagesByLocale[locale],
      media: { ...base.editor.media, ...rawLiteralOverrides.editor?.media },
      properties: base.editor.properties,
      reference: {
        ...base.editor.reference,
        ...bundle.reference,
      },
      slash: base.editor.slash,
      toolbar: {
        ...base.editor.toolbar,
        ...rawLiteralOverrides.editor?.toolbar,
      },
    },
    sidebar: { ...base.sidebar, ...rawLiteralOverrides.sidebar },
  };
}

// Only en-US is bundled eagerly. Locale modules call buildMessagesForLocale on
// load and register their merged messages here, so synchronous readers fall
// back to en-US until a locale chunk has loaded.
export const messagesByLocale: Partial<Record<LocaleCode, Messages>> & {
  "en-US": Messages;
} = {
  "en-US": enUS,
};

export function registerMessagesForLocale(
  locale: LocaleCode,
  messages: Messages,
) {
  messagesByLocale[locale] = messages;
}

export function buildMessagesForLocale(
  locale: Exclude<LocaleCode, "en-US">,
  overrides: PartialMessages,
  bundle: ContentLocaleBundle,
): Messages {
  const messages = mergeMessagesForLocale(locale, overrides, bundle);
  for (const [group, groupOverrides] of Object.entries(
    bundle.exactEnglish,
  ) as Array<[string, Record<string, unknown> | undefined]>) {
    const target = (messages as Record<string, Record<string, unknown>>)[group];
    if (target && groupOverrides && typeof groupOverrides === "object") {
      for (const [key, value] of Object.entries(groupOverrides)) {
        const nestedTarget = target[key];
        if (
          nestedTarget &&
          value &&
          typeof nestedTarget === "object" &&
          typeof value === "object" &&
          !Array.isArray(nestedTarget) &&
          !Array.isArray(value)
        ) {
          Object.assign(nestedTarget, value);
        } else {
          target[key] = value;
        }
      }
    }
  }
  Object.assign(messages.sidebar, bundle.sidebarPinned);
  Object.assign(messages.editor, bundle.history);
  registerMessagesForLocale(locale, messages);
  return messages;
}
