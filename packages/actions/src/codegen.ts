import fs from "node:fs";
import path from "node:path";

const SKIP_FILES = new Set([
  "context",
  "helpers",
  "index",
  "registry",
  "run",
  "types",
  "utils",
]);

const ACTION_EXTENSIONS = new Set([".ts", ".tsx", ".mts", ".js", ".mjs"]);

export interface ScannedActionFile {
  name: string;
  filePath: string;
  relativeImport: string;
  identifier: string;
}

export interface ScanActionsResult {
  actions: ScannedActionFile[];
  contextFile: string | null;
}

function toValidIdentifier(name: string, index: number): string {
  const cleaned = name.replace(/[^A-Za-z0-9_$]/g, "_");
  return `action_${index}_${cleaned}`;
}

function toPosixRelative(fromDir: string, targetFile: string): string {
  const withoutExt = targetFile.replace(/\.(?:tsx?|mts|mjs|js)$/, "");
  const rel = path.relative(fromDir, withoutExt).split(path.sep).join("/");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

export function scanActionsDirectory(
  projectRoot: string,
  options: { actionsDir?: string; generatedDir?: string } = {},
): ScanActionsResult {
  const actionsDir = path.resolve(projectRoot, options.actionsDir ?? "actions");
  const generatedDir = path.resolve(
    projectRoot,
    options.generatedDir ?? ".generated",
  );

  if (!fs.existsSync(actionsDir)) {
    return { actions: [], contextFile: null };
  }

  let contextFile: string | null = null;
  const entries = fs
    .readdirSync(actionsDir, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .sort((a, b) => a.name.localeCompare(b.name));

  const seenNames = new Map<string, string>();
  const actions: ScannedActionFile[] = [];

  for (const entry of entries) {
    if (
      entry.name.endsWith(".d.ts") ||
      entry.name.includes(".spec.") ||
      entry.name.includes(".test.") ||
      entry.name.startsWith("_") ||
      entry.name.startsWith(".")
    ) {
      continue;
    }

    const ext = path.extname(entry.name);
    if (!ACTION_EXTENSIONS.has(ext)) continue;

    const baseName = entry.name.slice(0, -ext.length);
    const fullPath = path.join(actionsDir, entry.name);

    if (baseName === "context") {
      contextFile = fullPath;
      continue;
    }

    if (SKIP_FILES.has(baseName)) continue;

    const existing = seenNames.get(baseName);
    if (existing) {
      throw new Error(
        `Duplicate action name "${baseName}" found in ${existing} and ${fullPath}.`,
      );
    }
    seenNames.set(baseName, fullPath);

    actions.push({
      name: baseName,
      filePath: fullPath,
      relativeImport: toPosixRelative(generatedDir, fullPath),
      identifier: toValidIdentifier(baseName, actions.length),
    });
  }

  return { actions, contextFile };
}

export interface GenerateArtifactsOptions {
  projectRoot: string;
  actionsDir?: string;
  generatedDir?: string;
}

export interface GenerateArtifactsResult {
  manifestPath: string;
  typesPath: string;
  actionCount: number;
  hasContextFile: boolean;
}

/**
 * Deterministically generate:
 * - `.generated/actions.ts`: static ES-import registry (`export const actions`, `export type AppActions`)
 * - `.generated/action-types.d.ts`: module augmentation for `ActionTypeRegistry`
 */
export function generateActionArtifacts(
  options: GenerateArtifactsOptions,
): GenerateArtifactsResult {
  const generatedDir = path.resolve(
    options.projectRoot,
    options.generatedDir ?? ".generated",
  );
  const scan = scanActionsDirectory(options.projectRoot, {
    ...(options.actionsDir ? { actionsDir: options.actionsDir } : {}),
    ...(options.generatedDir ? { generatedDir: options.generatedDir } : {}),
  });

  fs.mkdirSync(generatedDir, { recursive: true });

  const importLines = scan.actions.map(
    (action) =>
      `import ${action.identifier} from ${JSON.stringify(action.relativeImport)};`,
  );

  const contextImport = scan.contextFile
    ? `import * as actionContextModule from ${JSON.stringify(toPosixRelative(generatedDir, scan.contextFile))};`
    : "";

  const entriesLines = scan.actions.map(
    (action) => `  ${JSON.stringify(action.name)}: ${action.identifier},`,
  );

  const createContextLine = scan.contextFile
    ? `  ...(typeof actionContextModule.createContext === "function" ? { createContext: actionContextModule.createContext } : {}),`
    : "";

  const manifestSource = [
    "// Auto-generated by @agent-native/actions. Do not edit manually.",
    'import { createActions } from "@agent-native/actions";',
    ...importLines,
    ...(contextImport ? [contextImport] : []),
    "",
    "export const actions = createActions({",
    "  actions: {",
    ...entriesLines,
    "  },",
    ...(createContextLine ? [createContextLine] : []),
    "});",
    "",
    "export type AppActions = typeof actions;",
    "",
  ].join("\n");

  const typeImportLines = scan.actions.map(
    (action) =>
      `  ${JSON.stringify(action.name)}: typeof import(${JSON.stringify(action.relativeImport)}).default;`,
  );

  const typesSource = [
    "// Auto-generated by @agent-native/actions. Do not edit manually.",
    'import type { InferActionInputFromDef, InferActionReturn } from "@agent-native/actions";',
    "",
    "interface GeneratedActionDefinitions {",
    ...typeImportLines,
    "}",
    "",
    'declare module "@agent-native/actions/client" {',
    "  interface ActionTypeRegistry {",
    "    actions: {",
    "      [K in keyof GeneratedActionDefinitions]: {",
    "        input: InferActionInputFromDef<GeneratedActionDefinitions[K]>;",
    "        output: InferActionReturn<GeneratedActionDefinitions[K]>;",
    "      };",
    "    };",
    "  }",
    "}",
    "",
    "export {};",
    "",
  ].join("\n");

  const manifestPath = path.join(generatedDir, "actions.ts");
  const typesPath = path.join(generatedDir, "action-types.d.ts");

  writeFileIfChanged(manifestPath, manifestSource);
  writeFileIfChanged(typesPath, typesSource);

  return {
    manifestPath,
    typesPath,
    actionCount: scan.actions.length,
    hasContextFile: Boolean(scan.contextFile),
  };
}

function writeFileIfChanged(filePath: string, content: string): void {
  if (fs.existsSync(filePath)) {
    const existing = fs.readFileSync(filePath, "utf8");
    if (existing === content) return;
  }
  fs.writeFileSync(filePath, content, "utf8");
}
