import {
  readFileSync,
  readdirSync,
  realpathSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path, { join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const docsDir = join(__dirname, "..", "docs");

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, files);
    else if (name.endsWith(".md") || name === "llms.txt") files.push(full);
  }
  return files;
}

/**
 * Each doc with its path under docs/, in bundle order. Paths use forward
 * slashes and are sorted as such, so a Windows build writes the same bundle.
 */
export function bundleEntries(dir, files, pathApi = path) {
  return files
    .map((file) => ({
      file,
      rel: pathApi.relative(dir, file).split(pathApi.sep).join("/"),
    }))
    .sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0));
}

function main() {
  const entries = bundleEntries(docsDir, walk(docsDir));
  const out = [];
  out.push("# @agent-native/scheduling — Full Documentation Bundle");
  out.push("");
  out.push(
    "Generated by scripts/build-llms-full.mjs. Includes every markdown doc",
  );
  out.push("and skill. For a curated index, see llms.txt.");
  out.push("");
  for (const { file, rel } of entries) {
    if (file.endsWith("llms-full.txt")) continue;
    out.push(`\n---\n## ${rel}\n`);
    out.push(readFileSync(file, "utf8"));
  }
  writeFileSync(join(docsDir, "llms-full.txt"), out.join("\n"));
  console.log(
    `Wrote ${entries.length} files → docs/llms-full.txt (${out.join("\n").length} bytes)`,
  );
}

// Node resolves symlinks for import.meta.url but not for argv[1]; compare
// real paths, or a run through a linked path skips the build and exits 0.
if (
  process.argv[1] &&
  realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
