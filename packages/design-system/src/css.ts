import { COLOR_SCALES, COLORS } from "./catalog/props.js";
import { APPEARANCES } from "./themes/appearances.js";
import { SHADCN_SLOTS } from "./themes/shadcn.js";
import type { ThemeDefinition } from "./themes/types.js";
import { switchColorLiterals } from "./tokens/component-inputs.js";
import {
  createPalette,
  DEFAULT_PALETTE_INPUT,
  type Palette,
} from "./tokens/palette.js";
import {
  staticPrimitives,
  RADIUS_STEPS,
  TEXT_STYLES,
  textStyleDeclarations,
  type TokenMap,
} from "./tokens/primitives.js";
import {
  DENSITIES,
  densityTokens,
  RADIUS_PRESETS,
  radiusTokens,
  STANDARD_SHAPE_TOKENS,
} from "./tokens/roles.js";

const GENERATED_HEADER =
  "/* Generated by packages/design-system/scripts/build-css.ts from src/. Do not edit. */";

const COLOR_SCOPES = [".light", ".dark", "[data-palette]"] as const;

function block(selector: string, tokens: TokenMap, indent = ""): string {
  const entries = Object.entries(tokens);
  if (entries.length === 0) return "";
  const body = entries
    .map(([name, value]) => `${indent}  ${name}: ${value};`)
    .join("\n");
  const selectors = selector.split("\n").join(`\n${indent}`);
  return `${indent}${selectors} {\n${body}\n${indent}}`;
}

function p3Block(rules: string[]): string {
  const inner = rules
    .filter(Boolean)
    .map((rule) =>
      rule
        .split("\n")
        .map((line) => `    ${line}`)
        .join("\n"),
    )
    .join("\n\n");
  return `@supports (color: color(display-p3 1 1 1)) {\n  @media (color-gamut: p3) {\n${inner}\n  }\n}`;
}

function colorScopeTokens(scale: string): TokenMap {
  const tokens: TokenMap = {};
  for (let step = 1; step <= 12; step++) {
    tokens[`--accent-${step}`] = `var(--${scale}-${step})`;
  }
  for (let step = 1; step <= 12; step++) {
    tokens[`--accent-a${step}`] = `var(--${scale}-a${step})`;
  }
  tokens["--accent-contrast"] = `var(--${scale}-contrast)`;
  tokens["--accent-surface"] = `var(--${scale}-surface)`;
  tokens["--accent-solid"] = `var(--${scale}-solid)`;
  tokens["--accent-solid-hover"] = `var(--${scale}-solid-hover)`;
  tokens["--accent-text"] = `var(--${scale}-text)`;
  tokens["--accent-indicator"] = `var(--${scale}-indicator, var(--${scale}-9))`;
  tokens["--accent-track"] = `var(--${scale}-track, var(--${scale}-9))`;
  return tokens;
}

function colorScopesCss(): string[] {
  return COLORS.map((color) =>
    block(
      color === "accent"
        ? [":root", ...COLOR_SCOPES, `[data-color="accent"]`].join(",\n")
        : `[data-color="${color}"]`,
      colorScopeTokens(COLOR_SCALES[color]),
    ),
  );
}

function radiusStepTokens(): TokenMap {
  const tokens: TokenMap = {};
  RADIUS_STEPS.forEach((value, index) => {
    tokens[`--radius-${index + 1}`] = `calc(${value}px * var(--radius-factor))`;
  });
  return tokens;
}

const preset = (name: string, value: string) => `[${name}][${name}="${value}"]`;

/**
 * Primitives and presets: the static ramps, the default color scales in both
 * appearances (sRGB with P3 overrides), and the density, radius and corner
 * presets. Theme-independent.
 */
export function tokensCss(
  palette: Palette = createPalette(DEFAULT_PALETTE_INPUT),
): string {
  const sections: string[] = [GENERATED_HEADER];

  sections.push(
    block(":root", {
      "--radius-factor": "1",
      ...staticPrimitives(),
      ...switchColorLiterals,
    }),
  );

  sections.push(
    ":where(.light) { color-scheme: light; }",
    ":where(.dark) { color-scheme: dark; }",
  );
  sections.push(block(":root,\n.light", palette.light.srgb));
  sections.push(block(".dark", palette.dark.srgb));
  sections.push(
    p3Block([
      block(":root,\n.light", palette.light.p3),
      block(".dark", palette.dark.p3),
    ]),
  );

  sections.push(...colorScopesCss());

  sections.push(block(":root", densityTokens("default")));
  for (const density of DENSITIES) {
    sections.push(
      block(preset("data-density", density), densityTokens(density)),
    );
  }

  for (const radius of RADIUS_PRESETS) {
    const selectors = ":scope[data-radius],\n[data-app-theme][data-app-theme]";
    sections.push(
      `@scope ([data-radius="${radius}"]) {\n${block(
        selectors,
        {
          ...radiusStepTokens(),
          ...STANDARD_SHAPE_TOKENS,
          ...radiusTokens(radius),
        },
        "  ",
      )}\n}`,
    );
  }

  sections.push(
    block(preset("data-corners", "round"), {
      "--corner-shape": "round",
      "--corner-scale": "1",
    }),
  );
  sections.push(
    `@supports (corner-shape: superellipse(2)) {\n${block(
      preset("data-corners", "squircle"),
      {
        "--corner-shape": "superellipse(1.3)",
        "--corner-scale": "1.25",
      },
      "  ",
    )}\n}`,
  );

  return `${sections.filter(Boolean).join("\n\n")}\n`;
}

const NO_PALETTE = ":not([data-palette], [data-palette] *)";
const ROOT_LIGHT_SCALES = [":root", ".light"]
  .map((selector) => `${selector}${NO_PALETTE}`)
  .join(",\n");
const ROOT_DARK_SCALES = `.dark${NO_PALETTE}`;
function withResets(own: TokenMap, keys: ReadonlySet<string>): TokenMap {
  const tokens: TokenMap = { ...own };
  for (const key of keys) {
    if (!(key in tokens)) tokens[key as `--${string}`] = "initial";
  }
  return tokens;
}

/**
 * A theme's roles, values and tokens. The default theme is written twice:
 * unscoped, so it applies with no attribute, and inside `@scope`, like every
 * other theme, so the nearest `data-app-theme` ancestor wins by scope proximity.
 * The shared token inventory covers every theme that may enclose this one.
 */
export function themeCss(
  theme: ThemeDefinition,
  allThemes: readonly ThemeDefinition[] = [theme],
): string {
  const sections: string[] = [GENERATED_HEADER];
  const baseSelectors = (root: string) =>
    theme.readsScales ? [root, ...COLOR_SCOPES].join(",\n") : root;
  const appearanceKeys = new Set(
    allThemes.flatMap((other) => [
      ...Object.keys(other.base),
      ...Object.keys(other.dark),
      ...Object.keys(other.light),
    ]),
  );
  const tokenKeys = new Set(
    allThemes.flatMap((other) => Object.keys(other.tokens)),
  );

  if (theme.isDefault) {
    sections.push(block(baseSelectors(":root"), theme.base));
    sections.push(block(".dark", theme.dark));
    sections.push(block(".light", theme.light));
    sections.push(block(":root", theme.tokens));
    sections.push(
      block(ROOT_LIGHT_SCALES, {
        ...theme.palette.light.srgb,
        ...colorScopeTokens("brand"),
      }),
    );
    sections.push(
      block(ROOT_DARK_SCALES, {
        ...theme.palette.dark.srgb,
        ...colorScopeTokens("brand"),
      }),
    );
    sections.push(
      p3Block([
        block(ROOT_LIGHT_SCALES, theme.palette.light.p3),
        block(ROOT_DARK_SCALES, theme.palette.dark.p3),
      ]),
    );
  }

  const root = `[data-app-theme="${theme.name}"]`;
  const themeRoot = `:where(:scope)${root}`;
  const scoped = [
    block(
      baseSelectors(themeRoot),
      { ...withResets(theme.base, appearanceKeys), ...theme.scopedOnly?.base },
      "  ",
    ),
    block(themeRoot, withResets(theme.tokens, tokenKeys), "  "),
  ].filter(Boolean);
  const limit = theme.readsScales ? " to ([data-app-theme])" : "";
  sections.push(`@scope (${root})${limit} {\n${scoped.join("\n\n")}\n}`);

  const appearanceSelectors = (mode: string) => [
    `:scope:where(${root}) .${mode}`,
    `:scope:where(.${mode}) ${root}`,
    `:scope:where(.${mode})${root}`,
  ];
  const light = appearanceSelectors("light");
  const dark = appearanceSelectors("dark");
  const scales = (selectors: string[]) =>
    selectors.map((selector) => `${selector}${NO_PALETTE}`).join(",\n");
  const lightScales = scales([themeRoot, ...light]);
  const darkScales = scales(dark);
  const foreignSlots = new Set(
    [...appearanceKeys].filter(
      (key) => !(key in theme.base || key in theme.light || key in theme.dark),
    ),
  );
  const scopedLight: TokenMap = {};
  for (const key of Object.keys(
    theme.scopedOnly?.dark ?? {},
  ) as (keyof TokenMap)[]) {
    scopedLight[key] = theme.scopedOnly?.base[key] ?? "initial";
  }
  const appearances = [
    block(
      dark.join(",\n"),
      withResets({ ...theme.dark, ...theme.scopedOnly?.dark }, foreignSlots),
      "  ",
    ),
    block(
      light.join(",\n"),
      withResets({ ...theme.light, ...scopedLight }, foreignSlots),
      "  ",
    ),
    block(
      lightScales,
      { ...theme.palette.light.srgb, ...colorScopeTokens("brand") },
      "  ",
    ),
    block(
      darkScales,
      { ...theme.palette.dark.srgb, ...colorScopeTokens("brand") },
      "  ",
    ),
    p3Block([
      block(lightScales, theme.palette.light.p3),
      block(darkScales, theme.palette.dark.p3),
    ])
      .split("\n")
      .map((line) => `  ${line}`)
      .join("\n"),
  ].filter(Boolean);
  sections.push(
    `@scope (${root}, .light, .dark) {\n${appearances.join("\n\n")}\n}`,
  );

  return `${sections.filter(Boolean).join("\n\n")}\n`;
}

/**
 * The color tints (`data-appearance` on the root) as overrides of the active
 * theme's own values, so roles and the shadcn aliases both follow them. More
 * specific than any theme's root rules, in either appearance; the Agent-Native
 * theme opts out.
 */
export function appearancesCss(): string {
  const slots: ReadonlySet<string> = new Set(SHADCN_SLOTS);
  const own = (values: Readonly<Record<string, string>>): TokenMap => {
    const tokens: TokenMap = {};
    for (const [slot, value] of Object.entries(values)) {
      if (!slots.has(slot)) {
        throw new Error(`Appearance value "${slot}" is not a theme slot`);
      }
      tokens[`--theme-${slot}`] = value;
    }
    return tokens;
  };
  const sections: string[] = [GENERATED_HEADER];
  const optOut = ':not([data-app-theme="agent-native"])';
  for (const [name, { light, dark }] of Object.entries(APPEARANCES)) {
    sections.push(
      block(`:root[data-appearance="${name}"]${optOut}`, own(light)),
    );
    sections.push(
      block(`:root.dark[data-appearance="${name}"]${optOut}`, own(dark)),
    );
  }
  return `${sections.join("\n\n")}\n`;
}

export interface PaletteCssOptions {
  /** The `data-palette` value the CSS applies under. */
  id: string;
}

/**
 * Color scales generated from a brand color, scoped to `[data-palette="<id>"]`,
 * for a build step or a runtime `<style>` element. They restyle roles that
 * read the scales (the baseline theme's); a palette theme's colors are its
 * own values.
 */
export function paletteCss(
  palette: Palette,
  { id }: PaletteCssOptions,
): string {
  if (!/^[a-z0-9-]+$/i.test(id)) {
    throw new TypeError(`Palette id must be alphanumeric with dashes: ${id}`);
  }
  const scope = `[data-palette="${id}"]`;
  function selectors(mode: "light" | "dark") {
    const appearance =
      mode === "light" ? ":where(:root:not(.dark), .light)" : ":where(.dark)";
    return [
      `:scope${appearance}${scope}`,
      `:scope${appearance} ${scope}`,
      `:scope:where(${scope}) .${mode}:not(:where([data-palette]))`,
    ].join(",\n");
  }
  const light = selectors("light");
  const dark = selectors("dark");
  return [
    "@scope (:root, .light, .dark, [data-palette]) {",
    block(light, palette.light.srgb, "  "),
    block(dark, palette.dark.srgb, "  "),
    p3Block([block(light, palette.light.p3), block(dark, palette.dark.p3)]),
    "}",
  ].join("\n");
}

function declarations(
  properties: Readonly<Record<string, string>>,
  indent: string,
): string {
  return Object.entries(properties)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join("\n");
}

/** Text and Heading's `textStyle`: one rule per text style, in `@layer components`. */
export function textStylesCss(): string {
  const rules = TEXT_STYLES.map(
    (style) =>
      `  :is(.text, .heading)[data-text-style="${style.name}"] {\n${declarations(
        textStyleDeclarations(style),
        "    ",
      )}\n  }`,
  );
  return `${GENERATED_HEADER}\n\n@layer components {\n${rules.join("\n\n")}\n}\n`;
}

/** A Tailwind `type-<style>` utility per text style, for app chrome. */
export function textStyleUtilitiesCss(): string {
  const rules = TEXT_STYLES.map(
    (style) =>
      `@utility type-${style.name} {\n${declarations(
        textStyleDeclarations(style),
        "  ",
      )}\n}`,
  );
  return `${GENERATED_HEADER}\n\n${rules.join("\n\n")}\n`;
}
