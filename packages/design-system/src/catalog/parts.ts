/**
 * component: one control or element, named as Base UI names it, or as Radix
 * Themes does where Base UI has none.
 * pattern: a layout composed of components.
 */
export type PartKind = "component" | "pattern";

export type PartStatus = "built" | "planned";

export interface PartDefinition {
  /** Catalog name and root class: `menu` renders `.menu-*` classes. */
  name: string;
  kind: PartKind;
  /** Sub-part names; each renders as the `name-sub` class. */
  subParts: readonly string[];
  /** The Base UI module that supplies behavior, if any. */
  baseUi?: string;
  /** The toolkit module apps import today. */
  toolkit?: string;
  /** available: shipped and swapped in; built: on Base UI, not yet swapped; planned: still shadcn or app code. */
  status: PartStatus;
  /**
   * The component's props, as Radix Themes defines them. Each enum and
   * boolean prop is a data attribute the part CSS reads.
   */
  props?: PropDefs;
  /** Inherited CSS customization inputs and their stylesheet fallbacks. */
  cssInputs?: CssInputs;
  /** Props of a sub-part that takes its own, as Radix Themes' `Select.Content`. */
  subPartProps?: Readonly<Record<string, PropDefs>>;
  /** False for a pattern that only composes components and draws no CSS of its own. */
  stylesheet?: false;
  /** Data attributes the part's CSS reads beyond its props and Base UI's state attributes. */
  attributes?: Readonly<Record<string, readonly string[]>>;
}

const planned = (
  name: string,
  kind: PartKind,
  subParts: readonly string[],
  baseUi?: string,
  toolkit?: string,
): PartDefinition => ({
  name,
  kind,
  subParts,
  ...(baseUi === undefined ? {} : { baseUi }),
  ...(toolkit === undefined ? {} : { toolkit }),
  status: "planned",
});

