/** Every class a part reserves: `button`, `menu-popup`, `menu-item`, ... */
export function reservedClassNames(
  parts: readonly PartDefinition[] = PARTS,
): string[] {
  return parts.flatMap((part) => [
    part.name,
    ...part.subParts.map((sub) => `${part.name}-${sub}`),
  ]);
}

export function getPart(name: string): PartDefinition | undefined {
  return PARTS.find((part) => part.name === name);
}
