#!/usr/bin/env node
// Regenerates src/server/og-fonts-data.ts by base64-encoding the bundled
// OG image fonts. The fonts are embedded as base64 (rather than read
// from disk at runtime) so that OG image text renders consistently regardless
// of the host's system fonts or how the serverless bundle is traced — the
// font bytes always travel with the compiled JS. Run after updating the .ttf
// files in src/assets/fonts/:  node scripts/generate-og-font-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const fonts = [
  {
    constName: "LIBERATION_SANS_REGULAR_BASE64",
    file: "../src/assets/fonts/LiberationSans-Regular.ttf",
  },
  {
    constName: "LIBERATION_SANS_BOLD_BASE64",
    file: "../src/assets/fonts/LiberationSans-Bold.ttf",
  },
  {
    constName: "NOTO_NASKH_ARABIC_BASE64",
    file: "../src/assets/fonts/NotoNaskhArabic-Variable.ttf",
  },
  // The Geist faces are Latin subsets of the v1.7.2 release TTFs: every
  // serverless function that bundles @agent-native/core/server carries these
  // bytes, and they only draw the English sign-in copy. Regenerate with
  //   pyftsubset <ttf> --unicodes="U+0020-007E,U+00A0-00FF,U+2010-2027,U+2032-2033,U+20AC,U+2122" \
  //     --layout-features='*' --name-IDs='*' --name-languages='*' --name-legacy --no-hinting
  // (Geist Mono only needs U+0020-007E).
  {
    constName: "GEIST_REGULAR_BASE64",
    file: "../src/assets/fonts/Geist-Regular.ttf",
  },
  {
    constName: "GEIST_SEMIBOLD_BASE64",
    file: "../src/assets/fonts/Geist-SemiBold.ttf",
  },
  {
    constName: "GEIST_MONO_SEMIBOLD_BASE64",
    file: "../src/assets/fonts/GeistMono-SemiBold.ttf",
  },
];

const banner = `// AUTO-GENERATED by scripts/generate-og-font-data.mjs — do not edit by hand.
// Base64-encoded OG image fonts, embedded so the OG image renderer always has
// script coverage independent of host system fonts or serverless asset tracing.
// See src/assets/fonts/LICENSE_LIBERATION,
// src/assets/fonts/LICENSE_NOTO_NASKH_ARABIC, and src/assets/fonts/LICENSE_GEIST
// for licensing. Regenerate with:
//   node scripts/generate-og-font-data.mjs
`;

const body = fonts
  .map(({ constName, file }) => {
    const bytes = readFileSync(fileURLToPath(new URL(file, import.meta.url)));
    return `export const ${constName} =\n  "${bytes.toString("base64")}";`;
  })
  .join("\n\n");

const out = fileURLToPath(
  new URL("../src/server/og-fonts-data.ts", import.meta.url),
);
writeFileSync(out, `${banner}\n${body}\n`);
console.log(`Wrote ${out}`);
