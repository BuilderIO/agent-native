// guard:allow-unreleased-schema — renders a schema dump as text; never executes DDL
/**
 * Read a database's `public` schema back out of the catalog: as replayable SQL
 * (an upgrade fixture today, the Phase 2 install snapshot later) and as a
 * comparable fingerprint. Catalog queries only, so it works on PGlite, which
 * has no `pg_dump`.
 */

import type { DbExec } from "./client.js";

/** Tables whose rows are migration bookkeeping, dumped with their data. */
const BOOKKEEPING_TABLE =
  /(?:^_.*migrations?$|_migrations$|^_an_store_migrations$)/;

export interface SchemaFingerprint {
  tables: string[];
  columns: string[];
  indexes: string[];
  constraints: string[];
}

async function rows(exec: DbExec, sql: string) {
  return (await exec.execute(sql)).rows as Array<Record<string, unknown>>;
}

function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

function literal(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number" || typeof value === "bigint") {
    return String(value);
  }
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  return `'${String(value).replace(/'/g, "''")}'`;
}

const COLUMNS_SQL = `
  SELECT c.relname AS table_name, a.attname AS column_name,
         format_type(a.atttypid, a.atttypmod) AS type,
         a.attnotnull AS not_null, a.attidentity AS identity,
         pg_get_expr(d.adbin, d.adrelid) AS default_expr
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
   WHERE n.nspname = 'public' AND c.relkind = 'r'
     AND a.attnum > 0 AND NOT a.attisdropped
   ORDER BY c.relname, a.attnum`;

const CONSTRAINTS_SQL = `
  SELECT c.relname AS table_name, con.conname AS name, con.contype AS kind,
         pg_get_constraintdef(con.oid) AS definition
    FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND con.contype IN ('p', 'u', 'c', 'f')
   ORDER BY c.relname, con.conname`;

const INDEXES_SQL = `
  SELECT i.tablename AS table_name, i.indexname AS name, i.indexdef AS definition
    FROM pg_indexes i
   WHERE i.schemaname = 'public'
     AND NOT EXISTS (
       SELECT 1 FROM pg_constraint con
        WHERE con.conname = i.indexname AND con.contype IN ('p', 'u')
     )
   ORDER BY i.tablename, i.indexname`;

const SEQUENCES_SQL = `
  SELECT c.relname AS name FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relkind = 'S'
     AND NOT EXISTS (
       SELECT 1 FROM pg_depend d
        WHERE d.objid = c.oid AND d.deptype = 'i'
     )
   ORDER BY c.relname`;

const FUNCTIONS_SQL = `
  SELECT p.proname AS name, pg_get_functiondef(p.oid) AS definition
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'public'
     AND NOT EXISTS (
       SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e'
     )
   ORDER BY p.proname`;

const TRIGGERS_SQL = `
  SELECT t.tgname AS name, pg_get_triggerdef(t.oid) AS definition
    FROM pg_trigger t
    JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND NOT t.tgisinternal
   ORDER BY c.relname, t.tgname`;

/** Replayable SQL for the schema plus the rows of every bookkeeping table. */
export async function dumpSchemaSql(exec: DbExec): Promise<string> {
  const out: string[] = [];
  for (const seq of await rows(exec, SEQUENCES_SQL)) {
    out.push(`CREATE SEQUENCE IF NOT EXISTS ${quoteIdent(String(seq.name))};`);
  }
  const byTable = new Map<string, string[]>();
  for (const col of await rows(exec, COLUMNS_SQL)) {
    const table = String(col.table_name);
    const parts = [quoteIdent(String(col.column_name)), String(col.type)];
    if (col.identity === "a") parts.push("GENERATED ALWAYS AS IDENTITY");
    else if (col.identity === "d") {
      parts.push("GENERATED BY DEFAULT AS IDENTITY");
    } else if (col.default_expr != null) {
      parts.push(`DEFAULT ${String(col.default_expr)}`);
    }
    if (col.not_null === true || col.not_null === "t") parts.push("NOT NULL");
    const columns = byTable.get(table) ?? [];
    columns.push(parts.join(" "));
    byTable.set(table, columns);
  }
  for (const [table, columns] of byTable) {
    out.push(
      `CREATE TABLE ${quoteIdent(table)} (\n  ${columns.join(",\n  ")}\n);`,
    );
  }
  const constraints = await rows(exec, CONSTRAINTS_SQL);
  // Foreign keys last: they can point at tables created later in the dump.
  for (const con of [
    ...constraints.filter((c) => c.kind !== "f"),
    ...constraints.filter((c) => c.kind === "f"),
  ]) {
    out.push(
      `ALTER TABLE ${quoteIdent(String(con.table_name))} ADD CONSTRAINT ${quoteIdent(String(con.name))} ${String(con.definition)};`,
    );
  }
  for (const index of await rows(exec, INDEXES_SQL)) {
    out.push(`${String(index.definition)};`);
  }
  for (const fn of await rows(exec, FUNCTIONS_SQL)) {
    out.push(`${String(fn.definition).trim()};`);
  }
  for (const trigger of await rows(exec, TRIGGERS_SQL)) {
    out.push(`${String(trigger.definition)};`);
  }
  for (const table of [...byTable.keys()].filter((t) =>
    BOOKKEEPING_TABLE.test(t),
  )) {
    // guard:allow-unbounded-read — release tooling dumping migration bookkeeping, never a request path
    const data = await rows(exec, `SELECT * FROM ${quoteIdent(table)}`);
    for (const row of data) {
      const keys = Object.keys(row);
      out.push(
        `INSERT INTO ${quoteIdent(table)} (${keys.map(quoteIdent).join(", ")}) VALUES (${keys
          .map((key) => literal(row[key]))
          .join(", ")});`,
      );
    }
  }
  return `${out.join("\n\n")}\n`;
}

/** Order-independent description of the schema, for comparing two databases. */
export async function schemaFingerprint(
  exec: DbExec,
): Promise<SchemaFingerprint> {
  const columns = await rows(exec, COLUMNS_SQL);
  return {
    tables: [...new Set(columns.map((c) => String(c.table_name)))].sort(),
    columns: columns
      .map((c) => {
        const notNull = c.not_null === true || c.not_null === "t";
        const identity = c.identity ? ` identity:${c.identity}` : "";
        const defaultExpr =
          c.default_expr != null ? ` default ${c.default_expr}` : "";
        return `${c.table_name}.${c.column_name} ${c.type}${notNull ? " not null" : ""}${identity}${defaultExpr}`;
      })
      .sort(),
    indexes: (await rows(exec, INDEXES_SQL))
      .map((i) => String(i.definition))
      .sort(),
    constraints: (await rows(exec, CONSTRAINTS_SQL))
      .map((c) => `${c.table_name}.${c.name} ${c.definition}`)
      .sort(),
  };
}
